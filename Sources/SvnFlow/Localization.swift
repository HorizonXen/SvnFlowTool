func T(_ english: String, _ chinese: String, _ values: Any...) -> String {
    let template = InterfaceLanguage.code == "en" ? english : chinese
    let result = NSMutableString(string: template)
    let regex = try! NSRegularExpression(pattern: "\\{([0-9]+)\\}")
    for match in regex.matches(in: template, range: NSRange(location: 0, length: (template as NSString).length)).reversed() {
        let index = Int((template as NSString).substring(with: match.range(at: 1)))!
        if values.indices.contains(index) { result.replaceCharacters(in: match.range, with: String(describing: values[index])) }
    }
    return result as String
}

@MainActor private func localizedWindowTitle(_ title: String) -> String {
    if title.hasSuffix("设置") || title == "SVN Workbench Settings" { return AppIdentity.name + T(" Settings", "设置") }
    for (en, zh) in [("Compare — ", "比较 — "), ("Log — ", "日志 — "), ("Directory Changes — ", "目录差异 — ")] {
        for source in [en, zh] where title.hasPrefix(source) { return (InterfaceLanguage.code == "en" ? en : zh) + title.dropFirst(source.count) }
    }
    for source in [" — Table Compare", " — 表格比较"] where title.hasSuffix(source) {
        return title.dropLast(source.count) + T(" — Table Compare", " — 表格比较")
    }
    return L(title)
}
@MainActor func localizeSystemMenus() {
    guard let menu = NSApp.mainMenu else { return }
    func visit(_ menu: NSMenu, top: Bool) {
        for item in menu.items {
            if top && item.title == "显示" { item.title = T("View", "显示") }
            else if top && ["File", "文件", "Files"].contains(item.title) { item.title = T("File", "文件") }
            else { item.title = L(item.title) }
            if let submenu = item.submenu { submenu.title = item.title; visit(submenu, top: false) }
        }
    }
    visit(menu, top: true)
}
