}

enum InterfaceLanguage {
    static let key = "SvnFlow.interfaceLanguage"
    static var code: String { UserDefaults.standard.string(forKey: key) == "en" ? "en" : "zh-Hans" }
    @MainActor static func select(_ code: String) {
        UserDefaults.standard.set(code, forKey: key)
        for window in NSApp.windows { window.title = localizedWindowTitle(window.title) }
        DispatchQueue.main.async { localizeSystemMenus() }
    }
}
